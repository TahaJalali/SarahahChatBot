export function userLanguage(user) {
  return user && LANGUAGES.has(user.lang) ? user.lang : 'fa';
}

export function t(user, key, values = {}) {
  const lang = userLanguage(user);
  const template = strings[lang][key] ?? strings.en[key] ?? key;
  const vars = { brand: BOT_NAME, ...values };
  return template.replace(/\{([a-zA-Z]+)\}/g, (_, name) => String(vars[name] ?? ''));
}
